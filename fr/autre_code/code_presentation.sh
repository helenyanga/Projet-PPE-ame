        <h3>Choix du mot :</h3>
        <p class="has-text-primary-10">Nous avons choisi le mot "âme" par défaut car les autres mots qui nous intéressaient comme le mot "famille" par exemple, avaient déjà été utiliser comme sujet de projet. Par ailleurs, nous avons constater que ce mot serait inéressant car en effet, le mot "âme" désignerait plusieurs sens en français, en arabe et en russe. De plus, en arabe et en russe, nous retrouvons des mots ......................</p>
        <p class="has-text-primary-10">Le terme "âme" peut être employé dans plusieurs domaines tels que la science ou la spiritualisation par exemple. De plus, ce mot contient également plusieurs définitions. Selon le CRNTL (Centre National de Ressources Textuelles et Lexicales, 2012), le mot "âme" signifie d'abord, "un principe de vie" transcendant à l'humain (par exemple, la spiritualité) ; la seconde définition porterait sur le "principe immanent à l'homme" (par exemple, le principe de vie et de pensée ou les expressions comme "l'état d'âme" ou encore "vague à l'âme") et la dernière connotation est plutôt "technique et technologique" (par exemple, en musique on peut dire "âme d'un instrument à cordes").</p>
        <p>Lien de la source CNRTL : https://www.cnrtl.fr/definition/%C3%A2me</p>
